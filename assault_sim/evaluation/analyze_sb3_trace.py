from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path


def _load_trace(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _max_streak(values, target: str) -> int:
    best = 0
    cur = 0
    for v in values:
        if v == target:
            cur += 1
            best = max(best, cur)
        else:
            cur = 0
    return best


def analyze_trace(path: Path) -> None:
    payload = _load_trace(path)
    episodes = payload.get("episodes", []) or []
    if not episodes:
        print("No episodes found in trace.")
        return

    unit_slot_changes = 0
    unit_slot_total_edges = 0
    fallback_counts = Counter()
    block_profile_counts = Counter()
    episode_first_staging_turn = []
    episode_max_staging_streak = []
    episode_summary_rows = []

    for ep in episodes:
        trace = ep.get("trace", []) or []
        slots = [int((s.get("decision_action") or {}).get("unit_slot", 0)) for s in trace]
        for i in range(1, len(slots)):
            unit_slot_total_edges += 1
            if slots[i] != slots[i - 1]:
                unit_slot_changes += 1

        fallbacks = [
            str((s.get("capture_debug") or {}).get("fallback_reason") or "")
            for s in trace
        ]
        profiles = [
            str((s.get("capture_debug") or {}).get("move_block_profile") or "")
            for s in trace
        ]
        fallback_counts.update([x for x in fallbacks if x])
        block_profile_counts.update([x for x in profiles if x])

        staging_turn = None
        for s in trace:
            prof = str((s.get("capture_debug") or {}).get("move_block_profile") or "")
            if prof == "objective_staging_move":
                staging_turn = s.get("turn")
                break
        episode_first_staging_turn.append(staging_turn)
        episode_max_staging_streak.append(_max_streak(profiles, "objective_staging_move"))
        episode_summary_rows.append(
            {
                "episode": ep.get("episode"),
                "winner": ep.get("winner"),
                "end_reason": ep.get("end_reason"),
                "turn": ep.get("turn"),
                "steps": ep.get("steps"),
                "first_staging_turn": staging_turn,
                "max_staging_streak": episode_max_staging_streak[-1],
            }
        )

    slot_change_rate = (
        float(unit_slot_changes) / float(unit_slot_total_edges)
        if unit_slot_total_edges > 0 else 0.0
    )
    valid_first_staging = [t for t in episode_first_staging_turn if t is not None]
    avg_first_staging = (
        sum(valid_first_staging) / len(valid_first_staging)
        if valid_first_staging else None
    )
    avg_max_staging_streak = (
        sum(episode_max_staging_streak) / len(episode_max_staging_streak)
        if episode_max_staging_streak else 0.0
    )

    print("\n=== TRACE ANALYSIS ===")
    print(f"trace_file: {path}")
    print(f"episodes: {len(episodes)}")
    print(f"unit_slot_change_rate: {slot_change_rate:.3f} ({unit_slot_changes}/{unit_slot_total_edges})")
    if avg_first_staging is not None:
        print(f"avg_first_staging_turn: {avg_first_staging:.2f}")
    else:
        print("avg_first_staging_turn: n/a")
    print(f"avg_max_staging_streak: {avg_max_staging_streak:.2f}")

    print("\n--- TOP fallback_reason ---")
    if fallback_counts:
        for k, v in fallback_counts.most_common(8):
            print(f"{k}: {v}")
    else:
        print("(none)")

    print("\n--- TOP move_block_profile ---")
    if block_profile_counts:
        for k, v in block_profile_counts.most_common(8):
            print(f"{k}: {v}")
    else:
        print("(none)")

    print("\n--- EPISODE SUMMARY ---")
    for row in episode_summary_rows[:20]:
        print(
            f"ep={row['episode']} winner={row['winner']} reason={row['end_reason']} "
            f"turn={row['turn']} steps={row['steps']} "
            f"first_staging={row['first_staging_turn']} max_staging_streak={row['max_staging_streak']}"
        )


def main():
    parser = argparse.ArgumentParser(description="Analyze SB3 JSON trace output.")
    parser.add_argument("trace_path", type=str, help="Path to trace json generated by record_sb3_trace.py")
    args = parser.parse_args()
    analyze_trace(Path(args.trace_path))


if __name__ == "__main__":
    main()

